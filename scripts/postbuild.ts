// After `vite build`: sitemap.xml, blog/feed.xml (RSS 2.0), robots.txt, _redirects and
// meta-refresh stub pages for legacy non-article URLs. Reads .site/manifest.json from generate.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { site } from '../src/data/site.ts';
import { esc } from '../src/lib/html.ts';
import type { Manifest } from './generate.ts';

const ROOT = process.cwd();
const dist = join(ROOT, 'dist');
const m: Manifest = JSON.parse(readFileSync(join(ROOT, '.site/manifest.json'), 'utf8'));
const abs = (p: string) => site.url + p;
const xml = (s: string) => esc(s).replace(/&#39;/g, '&apos;');

function write(rel: string, data: string) {
  const f = join(dist, rel);
  mkdirSync(dirname(f), { recursive: true });
  writeFileSync(f, data);
}

// --- sitemap ---
const buildDay = m.buildIso.slice(0, 10);
const urls = [
  ...m.pages.map((p) => ({ loc: abs(p.path), lastmod: buildDay })),
  ...m.articles.map((a) => ({ loc: abs(a.path), lastmod: a.date.slice(0, 10) })),
];
write(
  'sitemap.xml',
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls
    .map((u) => `  <url><loc>${xml(u.loc)}</loc><lastmod>${u.lastmod}</lastmod></url>`)
    .join('\n')}\n</urlset>\n`,
);

// --- RSS ---
const items = m.articles
  .slice()
  .sort((a, b) => b.time - a.time)
  .map(
    (a) => `    <item>
      <title>${xml(a.title)}</title>
      <link>${xml(abs(a.path))}</link>
      <guid isPermaLink="true">${xml(abs(a.path))}</guid>
      <pubDate>${new Date(a.time).toUTCString()}</pubDate>
${a.author ? `      <dc:creator>${xml(a.author)}</dc:creator>\n` : ''}      <description>${xml(a.description)}</description>
    </item>`,
  )
  .join('\n');
write(
  'blog/feed.xml',
  `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:dc="http://purl.org/dc/elements/1.1/">
  <channel>
    <title>VitaminAir journal</title>
    <link>${abs('/blog/')}</link>
    <description>Notes, stories and older pieces from VitaminAir.</description>
    <language>en</language>
    <lastBuildDate>${new Date(m.buildIso).toUTCString()}</lastBuildDate>
    <atom:link href="${abs('/blog/feed.xml')}" rel="self" type="application/rss+xml"/>
${items}
  </channel>
</rss>
`,
);

// --- robots ---
write('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${abs('/sitemap.xml')}\n`);

// --- legacy routes ---
const redirects: [string, string][] = [
  ['/blog/home/', '/'],
  ['/blog/about/', '/village/'],
  ['/blog/contact/', '/contact/'],
  ['/blog/feed/rss', '/blog/feed.xml'],
];
const stubs: [string, string][] = [
  ['/blog/home/', '/'],
  ['/blog/about/', '/village/'],
  ['/blog/contact/', '/contact/'],
];
for (const c of ['leadership-and-personal-growth', 'community-and-recreation', 'forestry-and-nature']) stubs.push([`/blog/category/${c}/`, '/blog/']);
for (const t of ['posts', 'programs', 'personal-growth', 'projects', 'stories']) stubs.push([`/blog/tag/${t}/`, '/blog/']);
for (const a of ['2024', '2024-07', '2024-08', '2024-09']) stubs.push([`/blog/archive/${a}/`, '/blog/']);
stubs.push(['/blog/author/chas/', '/blog/']);
stubs.push(['/blog/feed/rss/', '/blog/feed.xml']);

const stubHtml = (to: string) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved · VitaminAir</title>
<meta name="robots" content="noindex">
<link rel="canonical" href="${esc(abs(to))}">
<meta http-equiv="refresh" content="0; url=${esc(to)}">
</head>
<body>
<p>This page has moved to <a href="${esc(to)}">${esc(abs(to))}</a>.</p>
</body>
</html>
`;
for (const [from, to] of stubs) write(join(from, 'index.html'), stubHtml(to));

// Netlify serves an existing file before a plain rule, so every rule is forced (301!). A stub exists at each
// legacy path (or under each wildcard), and the forced rule sends a real 301 instead of the meta-refresh page.
const rules: [string, string][] = [];
for (const [f, t] of redirects) {
  rules.push([f, t]);
  rules.push([f.endsWith('/') ? f.slice(0, -1) : f + '/', t]);
}
for (const w of ['category', 'tag', 'archive', 'author']) rules.push([`/blog/${w}/*`, '/blog/']);
const lines = [
  '# Netlify / Cloudflare Pages redirects. Generated by scripts/postbuild.ts',
  '# 301! forces the rule even where a meta-refresh stub file exists at the same path.',
  ...rules.map(([f, t]) => `${f} ${t} 301!`),
];
write('_redirects', [...new Set(lines)].join('\n') + '\n');

console.log(`postbuild: sitemap ${urls.length} urls, feed ${m.articles.length} items, ${stubs.length} legacy stubs, ${[...new Set(lines)].length - 2} redirect rules`);
